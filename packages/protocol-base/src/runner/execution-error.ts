export type RunnerExecutionError = z.infer<typeof RunnerExecutionErrorSchema>;

export type ExecutionCheckCode =
  | NonNullable<RunnerExecutionError["reason"]>
  | `execution_${RunnerExecutionError["code"]}`;

export function runnerExecutionCheck(error: RunnerExecutionError): ExecutionCheckCode {
  return error.reason ?? `execution_${error.code}`;
}
